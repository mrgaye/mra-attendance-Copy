-- MRA Attendance: Forgotten Clock-Out Correction System
-- Review before executing against PostgreSQL.

CREATE TABLE IF NOT EXISTS attendance_correction_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    attendance_id INTEGER NOT NULL
        REFERENCES attendance(id),

    employee_id INTEGER NOT NULL
        REFERENCES employees(id),

    original_clock_in TEXT NOT NULL,
    requested_clock_out TEXT NOT NULL,
    reason TEXT NOT NULL,

    status TEXT NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),

    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    reviewed_by INTEGER
        REFERENCES employees(id),

    reviewed_at TIMESTAMPTZ,
    review_remarks TEXT,

    approved_clock_out TEXT,

    CHECK (length(trim(reason)) > 0),

    CHECK (
        (status = 'PENDING'
         AND reviewed_by IS NULL
         AND reviewed_at IS NULL
         AND approved_clock_out IS NULL)
        OR
        (status = 'REJECTED'
         AND reviewed_by IS NOT NULL
         AND reviewed_at IS NOT NULL
         AND approved_clock_out IS NULL)
        OR
        (status = 'APPROVED'
         AND reviewed_by IS NOT NULL
         AND reviewed_at IS NOT NULL
         AND approved_clock_out IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS
    attendance_one_pending_correction
ON attendance_correction_requests (attendance_id)
WHERE status = 'PENDING';

CREATE INDEX IF NOT EXISTS
    attendance_corrections_employee_idx
ON attendance_correction_requests (employee_id, requested_at DESC);

CREATE INDEX IF NOT EXISTS
    attendance_corrections_status_idx
ON attendance_correction_requests (status, requested_at DESC);
